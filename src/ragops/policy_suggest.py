from __future__ import annotations

import json
from collections import Counter

from ragops.loader import ContractError
from ragops.models import EvaluationReport, Scenario
from ragops.slices import SliceSelector, summarize_slices

# Metrics that exist both globally and inside every slice, so one policy can gate both.
QUALITY_METRICS = ("citation_coverage", "citation_precision", "lexical_groundedness")


def suggest_release_policy(
    scenario: Scenario,
    baseline: EvaluationReport,
    *,
    margin: float = 0.05,
    min_cases: int = 3,
) -> str:
    """Render a release policy v2 (TOML) from an accepted baseline.

    One slice is created per language, category and severity value that has at least
    ``min_cases`` cases and does not cover the whole scenario. Because the policy applies one
    threshold per metric to every slice, each minimum is the lowest baseline value among the
    whole set and the included slices, minus ``margin``; the baseline therefore passes its own
    policy and a drop of more than ``margin`` against it is blocked.
    """
    if not 0 <= margin <= 1:
        raise ContractError("margin must be between 0 and 1")
    if min_cases < 1:
        raise ContractError("min_cases must be at least 1")
    total = len(scenario.cases)
    if total < 1:
        raise ContractError("Scenario has no cases")
    selectors = _selectors(scenario, min_cases)
    summaries = summarize_slices(scenario, baseline, tuple(selectors))
    lowest = {metric: baseline.metrics[metric] for metric in QUALITY_METRICS}
    for summary in summaries:
        for metric in QUALITY_METRICS:
            lowest[metric] = min(lowest[metric], summary.metrics[metric])
    lines = [
        "# Generated by `ragops policy-suggest` from an accepted baseline. Review before use.",
        f"# margin={margin:g}: a quality drop larger than this against the baseline is blocked.",
        "[release]",
        f"minimum_cases = {min(total, min_cases)}",
        'insufficient_evidence = "warn"',
        "",
    ]
    for metric in QUALITY_METRICS:
        floor = max(0.0, round(lowest[metric] - margin, 4))
        lines += [
            f"[metrics.{metric}]",
            'direction = "higher"',
            f"minimum = {floor:g}",
            f"max_regression = {margin:g}",
            "",
        ]
    for selector in selectors:
        lines.append("[[slices]]")
        lines.append(f"name = {json.dumps(selector.name)}")
        for field in ("language", "category", "severity"):
            value = getattr(selector, field)
            if value is not None:
                lines.append(f"{field} = {json.dumps(value)}")
        lines.append(f"minimum_cases = {min_cases}")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def _selectors(scenario: Scenario, min_cases: int) -> list[SliceSelector]:
    total = len(scenario.cases)
    selectors = []
    for field in ("language", "category", "severity"):
        counts = Counter(getattr(case, field) for case in scenario.cases)
        for value, count in sorted(counts.items()):
            if count >= min_cases and count < total:
                selectors.append(SliceSelector(name=f"{field}_{value}", **{field: value}))
    return selectors
